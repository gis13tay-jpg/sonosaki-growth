// 見出し付きセクション（contentSections）1つ分。paragraphsとlistは両方指定してもよい
export type ColumnSection = {
  heading: string
  paragraphs?: string[]
  list?: string[]
  ordered?: boolean
  // 本文途中に挿入する自然な導線（組織診断／個別相談／集客支援など）。
  // セクションの見出し・paragraphsをCTAの文脈として使い、直下にボタンを表示する
  cta?: {
    label: string
    href: string
  }
}

export type ColumnFAQ = {
  question: string
  answer: string
}

